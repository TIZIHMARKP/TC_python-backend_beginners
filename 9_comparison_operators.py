# ===================  Comparison Operators ===================
#  Operators are: ==, !=, >, <, >=, <=
# Comparison Operators answers are always booleans i.e True or False

x = 10
y = 3

print(x == y)   # F
print(x != y)   # T
print(x > y)    # T
print(x < y)    # F
print(x <= y)   # F 
print(x >= y)   # T

